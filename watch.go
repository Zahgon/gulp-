// pollInterval is how often a Watcher scans the watched paths for changes.
const pollInterval = 50 * time.Millisecond

// Watcher watches files (the chokidar 3.6 FSWatcher gulp.watch returns), implemented by polling.
type Watcher struct {
	roots   []watchRoot
	ignored []*glob.Matcher
	cwd     string // "" when the cwd option is unset
	atomic  bool   // chokidar's atomic option: ignore editor swap files

	mu     sync.Mutex
	closed bool
	stop   chan struct{}
	state  map[string]entryState // the scan taken when the watcher was created

	// loop goroutine only
	listeners   map[string][]func(event, path string)
	errorFns    []func(error)
	initialErrs []error // file system errors of the first scan, delivered once listeners can be attached
	unreported  error   // first file system error no error listener received (guarded by mu)
	refed       bool
}

// watchRoot is one positive path or glob being watched.
type watchRoot struct {
	path     string        // directory or file scanned (internal form: absolute with cwd, else as given)
	matcher  *glob.Matcher // nil for a plain path
	maxDepth int           // directory levels below path to scan, -1 for unlimited
	isGlob   bool
}

// entryState is what the poller compares between scans.
type entryState struct {
	dir   bool
	size  int64
	mtime time.Time
	ino   uint64
	mode  os.FileMode
}

// Watch watches globs (a string or []string, negated globs excluded) and runs task, wrapped in Parallel so the
// command line logs it, after changes settle (gulp.watch over glob-watcher 6). Options are glob-watcher's and
// chokidar's: delay (ms, default 200), queue (default true), events (default add, change, unlink),
// ignoreInitial (default true), ignored, cwd, atomic (default true: editor swap files are ignored, as chokidar
// does on Linux). task may be nil, a *Task or a TaskFunc; a name or a list of names returns the original's error
// "watching <globs>: watch task has to be a function (optionally generated by using gulp.parallel or
// gulp.series)", and any other value is ignored, as the original ignores a task argument that is not a function.
// globs of another type return an error. The watcher keeps a command line run alive until it is closed.
func (g *Gulp) Watch(globs any, opts vfs.Options, task any) (*Watcher, error) {
	switch task.(type) {
	case string, []string, []any:
		return nil, fmt.Errorf("watching %s: watch task has to be a function (optionally generated by using gulp.parallel or gulp.series)", globText(globs))
	}
	var fn *Task
	switch v := task.(type) {
	case *Task:
		if v != nil && v.Fn != nil {
			fn = v
		}
	case TaskFunc:
		if v != nil {
			fn = &Task{Fn: v}
		}
	case func(Done):
		if v != nil {
			fn = &Task{Fn: v}
		}
	}
	var run *Task
	if fn != nil {
		p, err := g.Parallel(fn)
		if err != nil {
			return nil, err
		}
		run = p
	}
	o, err := watchOptions(opts)
	if err != nil {
		return nil, err
	}
	list, err := globList(globs)
	if err != nil {
		return nil, err
	}
	w, err := newWatcher(list, o)
	if err != nil {
		return nil, err
	}
	eventloop.OnHalt(w.stopPolling)
	eventloop.Dispatch(func() {
		w.ref()
		w.registerTask(o, run)
		w.initialEvents(o.ignoreInitial)
	})
	if errs := w.initialErrs; len(errs) > 0 {
		eventloop.Post(func() {
			for _, err := range errs {
				w.deliverError(err)
			}
		})
	}
	go w.poll()
	return w, nil
}

// globText is String(glob) for the error message.
func globText(globs any) string {
	switch v := globs.(type) {
	case string:
		return v
	case []string:
		return strings.Join(v, ",")
	}
	s, _ := jsKey(globs)
	return s
}

func globList(globs any) ([]string, error) {
	switch v := globs.(type) {
	case string:
		return []string{v}, nil
	case []string:
		return append([]string(nil), v...), nil
	case []any:
		out := make([]string, 0, len(v))
		for _, x := range v {
			s, ok := x.(string)
			if !ok {
				return nil, errors.New("watch: globs must be strings")
			}
			out = append(out, s)
		}
		return out, nil
	}
	return nil, errors.New("watch: globs must be a string or an array of strings")
}

// watchConfig follows glob-watcher's defaults merged with the given options (Object.assign semantics: a key present
// with a nil value is undefined and overrides the default).
type watchConfig struct {
	delay         time.Duration
	events        []string
	queue         bool
	ignoreInitial bool
	ignored       []string
	cwd           string
	atomic        bool
}

// watchOptions reads glob-watcher's and chokidar's options with their defaults; the error reports a cwd option that
// is not a string.
func watchOptions(opts vfs.Options) (watchConfig, error) {
	c := watchConfig{delay: 200 * time.Millisecond, events: []string{"add", "change", "unlink"}, queue: true,
		ignoreInitial: true, atomic: true}
	if v, ok := opts["atomic"]; ok {
		c.atomic = truthy(v)
	}
	if v, ok := opts["delay"]; ok {
		c.delay = timeoutDuration(v)
	}
	if v, ok := opts["events"]; ok {
		switch e := v.(type) {
		case []string:
			c.events = append([]string(nil), e...)
		case string:
			c.events = []string{e}
		case []any:
			c.events = nil
			for _, x := range e {
				if s, isString := x.(string); isString {
					c.events = append(c.events, s)
				}
			}
		default:
			c.events = nil
		}
	}
	if v, ok := opts["queue"]; ok {
		c.queue = truthy(v)
	}
	if v, ok := opts["ignoreInitial"]; ok {
		c.ignoreInitial = truthy(v)
	}
	switch v := opts["ignored"].(type) {
	case string:
		c.ignored = []string{v}
	case []string:
		c.ignored = append([]string(nil), v...)
	case []any:
		for _, x := range v {
			if s, isString := x.(string); isString {
				c.ignored = append(c.ignored, s)
			}
		}
	}
	if v, present := opts["cwd"]; present && v != nil {
		s, ok := v.(string)
		if !ok {
			// chokidar resolves paths with path.relative(cwd, ...), which throws for a cwd that is not a string.
			return c, fmt.Errorf("The \"cwd\" option must be of type string. Received %T", v)
		}
		c.cwd = s
	}
	return c, nil
}

// timeoutDuration is setTimeout's delay coercion: non-numbers and values outside [1, 2^31-1] become 1 ms.
func timeoutDuration(v any) time.Duration {
	var ms float64
	switch x := v.(type) {
	case int:
		ms = float64(x)
	case int64:
		ms = float64(x)
	case float64:
		ms = x
	case time.Duration:
		ms = float64(x) / float64(time.Millisecond)
	default:
		ms = math.NaN()
	}
	if !(ms >= 1 && ms <= 1<<31-1) {
		ms = 1
	}
	return time.Duration(ms * float64(time.Millisecond))
}

// truthy is JavaScript truthiness for option values.
func truthy(v any) bool {
	switch x := v.(type) {
	case nil:
		return false
	case bool:
		return x
	case string:
		return x != ""
	case int:
		return x != 0
	case float64:
		return x != 0 && !math.IsNaN(x)
	}
	return true
}

// swapFile follows chokidar's DOT_RE: editor swap and temporary files ignored in atomic mode.
var swapFile = regexp.MustCompile(`\..*\.(sw[px])$|~$|\.subl.*\.tmp`)

func newWatcher(globs []string, c watchConfig) (*Watcher, error) {
	w := &Watcher{
		stop:      make(chan struct{}),
		state:     map[string]entryState{},
		listeners: map[string][]func(string, string){},
		atomic:    c.atomic,
	}
	if c.cwd != "" {
		abs, err := nodepath.Resolve(c.cwd)
		if err != nil {
			return nil, err
		}
		w.cwd = abs
	}
	var ignored []string
	for _, p := range globs {
		neg := strings.HasPrefix(p, "!")
		if neg {
			p = p[1:]
		}
		p = w.internalPath(p)
		if neg {
			ignored = append(ignored, p)
			if !glob.IsGlob(p) {
				ignored = append(ignored, p+"/**")
			}
			continue
		}
		root := watchRoot{path: p, maxDepth: -1}
		if glob.IsGlob(p) {
			m, err := glob.NewMatcher([]string{p}, glob.Options{Dot: true})
			if err != nil {
				return nil, err
			}
			root.isGlob = true
			root.matcher = m
			root.path = glob.Parent(p)
			rest := strings.TrimPrefix(strings.TrimPrefix(p, root.path), "/")
			if !strings.Contains(rest, "**") {
				root.maxDepth = strings.Count(rest, "/")
			}
		}
		w.roots = append(w.roots, root)
	}
	for _, p := range c.ignored {
		ip := p
		if !nodepath.IsAbs(ip) {
			ip = nodepath.Join(w.cwd, ip)
		}
		ignored = append(ignored, ip)
		if !glob.IsGlob(ip) {
			ignored = append(ignored, ip+"/**")
		}
	}
	for _, p := range ignored {
		m, err := glob.NewMatcher([]string{p}, glob.Options{Dot: true})
		if err != nil {
			return nil, err
		}
		w.ignored = append(w.ignored, m)
	}
	w.state, w.initialErrs = w.scan()
	return w, nil
}

// internalPath is the path chokidar works with: resolved against cwd (absolute) when the option is set, otherwise
// the normalised path as given.
func (w *Watcher) internalPath(p string) string {
	if w.cwd != "" {
		return nodepath.ResolveIn(w.cwd, p)
	}
	return nodepath.Normalize(p)
}

// reportPath is the path an event reports: relative to cwd when the option is set.
func (w *Watcher) reportPath(p string) string {
	if w.cwd != "" {
		return nodepath.RelativeIn(w.cwd, w.cwd, p)
	}
	return p
}

func (w *Watcher) isIgnored(p string) bool {
	if w.atomic && swapFile.MatchString(p) {
		return true
	}
	for _, m := range w.ignored {
		if m.Index(p) >= 0 {
			return true
		}
	}
	return false
}

// scan collects the state of every watched entry. Entries that do not exist (or vanished while the scan ran) are
// simply absent, as chokidar treats ENOENT and ENOTDIR; every other file system error is returned for the
// watcher's error listeners.
func (w *Watcher) scan() (map[string]entryState, []error) {
	out := map[string]entryState{}
	var errs []error
	for _, r := range w.roots {
		info, err := os.Stat(r.path)
		if err != nil {
			errs = appendScanError(errs, err)
			continue
		}
		if !r.isGlob {
			if w.isIgnored(r.path) {
				continue
			}
			if !info.IsDir() {
				out[r.path] = stateOf(info)
				continue
			}
			out[r.path] = stateOf(info)
			errs = w.walk(r, r.path, 0, out, errs)
			continue
		}
		if info.IsDir() {
			if r.matcher.Index(r.path) >= 0 && !w.isIgnored(r.path) {
				out[r.path] = stateOf(info)
			}
			errs = w.walk(r, r.path, 0, out, errs)
		}
	}
	return out, errs
}

// appendScanError adds err to errs unless it only says the entry is missing, which a scan expects.
func appendScanError(errs []error, err error) []error {
	if errors.Is(err, os.ErrNotExist) || errors.Is(err, syscall.ENOTDIR) {
		return errs
	}
	return append(errs, err)
}

// walk records the entries below dir that the root watches and returns errs with the file system errors met.
func (w *Watcher) walk(r watchRoot, dir string, depth int, out map[string]entryState, errs []error) []error {
	entries, err := os.ReadDir(dir)
	if err != nil {
		return appendScanError(errs, err)
	}
	for _, e := range entries {
		p := nodepath.Join(dir, e.Name())
		if w.isIgnored(p) {
			continue
		}
		info, err := os.Stat(p)
		if err != nil {
			errs = appendScanError(errs, err)
			continue
		}
		if !r.isGlob || r.matcher.Index(p) >= 0 {
			out[p] = stateOf(info)
		}
		if info.IsDir() && (r.maxDepth < 0 || depth < r.maxDepth) {
			errs = w.walk(r, p, depth+1, out, errs)
		}
	}
	return errs
}

// fsEvent is one change the poller found.
type fsEvent struct {
	name string
	path string
}

// diff lists the events between two scans: removals in path order, then additions and changes in modification
// order (the order the file system reported them in), ties in path order.
func diff(old, cur map[string]entryState) []fsEvent {
	var removed, touched []string
	for p, s := range old {
		n, ok := cur[p]
		switch {
		case !ok || n.dir != s.dir:
			removed = append(removed, p)
			if ok {
				touched = append(touched, p)
			}
		case !n.dir && (n.size != s.size || !n.mtime.Equal(s.mtime) || n.ino != s.ino || n.mode != s.mode):
			touched = append(touched, p)
		}
	}
	for p := range cur {
		if _, ok := old[p]; !ok {
			touched = append(touched, p)
		}
	}
	sort.Strings(removed)
	sort.Slice(touched, func(a, b int) bool {
		ta, tb := cur[touched[a]].mtime, cur[touched[b]].mtime
		if !ta.Equal(tb) {
			return ta.Before(tb)
		}
		return touched[a] < touched[b]
	})
	var out []fsEvent
	for _, p := range removed {
		name := "unlink"
		if old[p].dir {
			name = "unlinkDir"
		}
		out = append(out, fsEvent{name, p})
	}
	for _, p := range touched {
		s, existed := old[p]
		name := "change"
		switch {
		case !existed || s.dir != cur[p].dir:
			name = "add"
			if cur[p].dir {
				name = "addDir"
			}
		}
		out = append(out, fsEvent{name, p})
	}
	return out
}

// poll scans every pollInterval until the watcher is closed and delivers the events on the loop.
func (w *Watcher) poll() {
	ticker := time.NewTicker(pollInterval)
	defer ticker.Stop()
	prev := w.snapshot()
	for {
		select {
		case <-w.stop:
			return
		case <-ticker.C:
		}
		cur, errs := w.scan()
		events := diff(prev, cur)
		prev = cur
		if len(events) == 0 && len(errs) == 0 {
			continue
		}
		eventloop.Post(func() {
			for _, e := range events {
				w.deliver(e.name, e.path)
			}
			for _, err := range errs {
				w.deliverError(err)
			}
		})
	}
}

func (w *Watcher) snapshot() map[string]entryState {
	w.mu.Lock()
	defer w.mu.Unlock()
	out := make(map[string]entryState, len(w.state))
	for k, v := range w.state {
		out[k] = v
	}
	return out
}

// initialEvents emits add and addDir for the entries found at start when ignoreInitial is off, then ready.
func (w *Watcher) initialEvents(ignoreInitial bool) {
	if ignoreInitial {
		eventloop.Post(func() { w.deliver("ready", "") })
		return
	}
	snap := w.snapshot()
	paths := make([]string, 0, len(snap))
	for p := range snap {
		paths = append(paths, p)
	}
	sort.Strings(paths)
	eventloop.Post(func() {
		for _, p := range paths {
			name := "add"
			if snap[p].dir {
				name = "addDir"
			}
			w.deliver(name, p)
		}
		w.deliver("ready", "")
	})
}

// deliver emits one event to the listeners of its name, then to the "all" listeners.
func (w *Watcher) deliver(name, p string) {
	if w.isClosed() {
		return
	}
	rel := ""
	if name != "ready" {
		rel = w.reportPath(p)
	}
	for _, fn := range append([]func(string, string){}, w.listeners[name]...) {
		fn(name, rel)
	}
	if name != "ready" {
		for _, fn := range append([]func(string, string){}, w.listeners["all"]...) {
			fn(name, rel)
		}
	}
}

// registerTask wires the debounced, queued task run (glob-watcher's registerWatchEvent).
func (w *Watcher) registerTask(c watchConfig, run *Task) {
	if run == nil {
		return
	}
	queued, running := false, false
	var onChange func()
	runComplete := func(err error) {
		running = false
		if err != nil {
			for _, fn := range append([]func(error){}, w.errorFns...) {
				fn(err)
			}
		}
		if queued {
			queued = false
			onChange()
		}
		// released last, so a queued run keeps the command line alive
		eventloop.Unref()
	}
	onChange = func() {
		if running {
			if c.queue {
				queued = true
			}
			return
		}
		running = true
		eventloop.Ref()
		asyncDone(run, runComplete)
	}
	var timer *eventloop.Timer
	debounced := func(string, string) {
		timer.Stop()
		timer = eventloop.AfterFunc(c.delay, func() {
			timer = nil
			onChange()
		})
	}
	for _, e := range c.events {
		w.listeners[e] = append(w.listeners[e], debounced)
	}
}

// On adds a listener for a chokidar event: "add", "change", "unlink", "addDir", "unlinkDir" (fn receives the
// path, relative to the cwd option when it is set), "all" (every one of those), "ready" (path ""), or "error"
// (fn receives the error text of a failed task run or of a file system error met while watching).
// Listeners run on the loop goroutine.
func (w *Watcher) On(event string, fn func(path string)) {
	if fn == nil {
		return
	}
	if event == "error" {
		w.OnError(func(err error) { fn(err.Error()) })
		return
	}
	eventloop.Dispatch(func() {
		w.listeners[event] = append(w.listeners[event], func(_, p string) { fn(p) })
	})
}

// OnAll adds a listener for every add, change, unlink, addDir and unlinkDir event with the event's name (the
// "all" event).
func (w *Watcher) OnAll(fn func(event, path string)) {
	if fn == nil {
		return
	}
	eventloop.Dispatch(func() {
		w.listeners["all"] = append(w.listeners["all"], fn)
	})
}

// OnError adds a listener for the errors of failed task runs (glob-watcher emits them only when an error
// listener exists) and for file system errors met while watching, other than missing entries.
func (w *Watcher) OnError(fn func(err error)) {
	if fn == nil {
		return
	}
	eventloop.Dispatch(func() {
		w.errorFns = append(w.errorFns, fn)
	})
}

func (w *Watcher) isClosed() bool {
	w.mu.Lock()
	defer w.mu.Unlock()
	return w.closed
}

func (w *Watcher) ref() {
	w.refed = true
	eventloop.Ref()
}

// stopPolling ends the polling goroutine without touching the event loop; the loop calls it when it halts.
func (w *Watcher) stopPolling() {
	w.mu.Lock()
	defer w.mu.Unlock()
	if !w.closed {
		w.closed = true
		close(w.stop)
	}
}

// Close stops watching. A task run already scheduled by the debounce still happens, as in the original. Close
// returns the first file system error met while watching that no error listener received (nil otherwise);
// closing twice is allowed.
func (w *Watcher) Close() error {
	w.mu.Lock()
	unreported := w.unreported
	if w.closed {
		w.mu.Unlock()
		return unreported
	}
	w.closed = true
	close(w.stop)
	w.mu.Unlock()
	eventloop.Dispatch(func() {
		if w.refed {
			w.refed = false
			eventloop.Unref()
		}
	})
	return unreported
}

// stateOf extracts what the poller compares from a stat result.
func stateOf(info os.FileInfo) entryState {
	s := entryState{dir: info.IsDir(), size: info.Size(), mtime: info.ModTime(), mode: info.Mode()}
	if st, ok := info.Sys().(*syscall.Stat_t); ok {
		s.ino = uint64(st.Ino)
	}
	return s
}

// deliverError passes a file system error of a scan to the error listeners (chokidar's "error" event). With no
// listener the first such error is kept for Close to return.
func (w *Watcher) deliverError(err error) {
	if w.isClosed() {
		return
	}
	if len(w.errorFns) == 0 {
		w.mu.Lock()
		if w.unreported == nil {
			w.unreported = err
		}
		w.mu.Unlock()
		return
	}
	for _, fn := range append([]func(error){}, w.errorFns...) {
		fn(err)
	}
}
